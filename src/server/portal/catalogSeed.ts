function makeProduct(input: {
  id: string;
  categoryId: string;
  categorySlug: string;
  slug: string;
  name: string;
  shortDescription: string;
  fullDescription: string;
  usd: number;
  isCustomQuote?: boolean;
  billingType?: 'one_time' | 'subscription_monthly' | 'credit_pack';
  creditsIncluded?: number;
  turnaroundLabel: string;
  revisionLimit: number;
  supportLevel: string;
  usageLimits: string;
  deliveryConditions: string;
  validityDays?: number;
  features: string[];
  sampleDeliverables: string[];
  requiredClientMaterials: string[];
  isFeatured?: boolean;
  isPopular?: boolean;
}): ProductRecord {
  const usdMinor = input.isCustomQuote ? 0 : Math.round(input.usd * 100);
  const phpMinor = input.isCustomQuote ? 0 : usdToPhpMinor(usdMinor);
  return {
    id: input.id,
    categoryId: input.categoryId,
    categorySlug: input.categorySlug,
    slug: input.slug,
    name: input.name,
    shortDescription: input.shortDescription,
    fullDescription: input.fullDescription,
    sampleDeliverables: input.sampleDeliverables,
    requiredClientMaterials: input.requiredClientMaterials,
    termsSummary:
      'Deliverables include commercial usage rights upon verified payment completion. Revision allowances apply per package scope; statutory consumer protections under Philippine law are preserved.',
    faqs: [
      {
        question: 'When does production start after placing an order?',
        answer:
          'Production begins once payment is verified by the server and your project brief is submitted in the My Projects workspace.',
      },
      {
        question: 'How do revisions work?',
        answer:
          'You can submit structured revision requests directly against any uploaded deliverable inside your project workspace within your package revision allowance.',
      },
      {
        question: 'Can I upload reference brand assets?',
        answer:
          'Yes. You can attach briefs, images, videos, or ZIP archives securely during checkout or at any time inside your private project workspace.',
      },
    ],
    isActive: true,
    isFeatured: Boolean(input.isFeatured),
    packages: [
      {
        id: `pkg-${input.slug}`,
        productId: input.id,
        name: input.name,
        tierCode: input.slug.toUpperCase().replace(/-/g, '_'),
        priceUsdMinor: usdMinor,
        pricePhpMinor: phpMinor,
        isCustomQuote: Boolean(input.isCustomQuote),
        billingType: input.billingType || 'one_time',
        creditsIncluded: input.creditsIncluded ?? 0,
        turnaroundLabel: input.turnaroundLabel,
        validityDays: input.validityDays,
        revisionLimit: input.revisionLimit,
        usageLimits: input.usageLimits,
        deliveryConditions: input.deliveryConditions,
        supportLevel: input.supportLevel,
        features: input.features,
        isPopular: input.isPopular,
        isIllustrativePricing: true,
      },
    ],
    createdAt: nowIso,
    updatedAt: nowIso,
  };
}

